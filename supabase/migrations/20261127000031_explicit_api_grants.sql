-- Explicit privileges for the API roles (anon, authenticated, service_role).
--
-- Local Supabase grants these by default on everything `postgres` creates in
-- `public`; newer hosted projects (our staging project) do not: tables get no
-- SELECT/INSERT/UPDATE/DELETE, sequences no usage and functions no EXECUTE, so
-- every API call failed with "permission denied". Row Level Security is what
-- protects the data; these grants only let the roles reach it.
--
-- The statements below were generated from the local database after all
-- earlier migrations, so they keep every restriction those migrations made
-- (column-only UPDATE on profiles and notifications, functions revoked from
-- anon or public, ...). On local Supabase this migration changes nothing.
-- Generator: supabase/scripts/api_grants.sql (docs/DATABASE.md, "Privileges").

-- New objects get the same privileges everywhere (local already does this).
alter default privileges for role postgres in schema public
  grant select, insert, update, delete on tables to anon, authenticated, service_role;
alter default privileges for role postgres in schema public
  grant usage, select, update on sequences to anon, authenticated, service_role;
alter default privileges for role postgres in schema public
  grant execute on functions to anon, authenticated, service_role;

